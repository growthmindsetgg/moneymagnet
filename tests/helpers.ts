export function strip(s: TokenSnapshot, metrics: (keyof TokenSnapshot)[]): TokenSnapshot {
  const out = { ...s } as Record<string, unknown>;
  for (const m of metrics) out[m] = null;
  return out as unknown as TokenSnapshot;
}
